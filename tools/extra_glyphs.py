import math, re

AXIS = -7.6          # ось стрелок и знака × — середина строчных


def _shift(d, dx):
    out, i = [], 0
    for tok in re.findall(r'[MLQ]|-?\d+(?:\.\d+)?', d):
        if tok in 'MLQ': out.append(tok); i = 0; continue
        v = float(tok) + (dx if i % 2 == 0 else 0); i += 1
        out.append(f'{v:.2f}')
    s = ' '.join(out)
    return re.sub(r'([MLQ]) ', r'\1', s).replace(' ', ',').replace(',M', ' M').replace(',L', ' L').replace(',Q', ' Q')


def _arc(cx, cy, r, a0=0, a1=360, n=8):
    """Дуга квадратичными кусками (y вниз), углы в градусах против часовой на экране."""
    pts = []
    step = (a1 - a0) / n
    P = lambda a: (cx + r * math.cos(math.radians(a)), cy - r * math.sin(math.radians(a)))
    x0, y0 = P(a0); s = f'M{x0:.2f},{y0:.2f}'
    k = r / math.cos(math.radians(step / 2))
    for j in range(n):
        am = a0 + step * (j + 0.5); a = a0 + step * (j + 1)
        cx1, cy1 = cx + k * math.cos(math.radians(am)), cy - k * math.sin(math.radians(am))
        x, y = P(a); s += f' Q{cx1:.2f},{cy1:.2f} {x:.2f},{y:.2f}'
    return s


